BASE_DIR = r"c:\Users\admin\Desktop\NeuroLoft\NEURO-ESTATE\ТЭО_Родовое_Поместье_Кейс"

def update_file(filename, replacement_dict):
    filepath = os.path.join(BASE_DIR, filename)
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    for old_pattern, new_text in replacement_dict.items():
        if isinstance(old_pattern, re.Pattern):
            content = old_pattern.sub(new_text, content)
        else:
            if old_pattern in content:
                content = content.replace(old_pattern, new_text)

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"Updated {filename}")

